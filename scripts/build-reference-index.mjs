#!/usr/bin/env node
// Builds compact heading indexes for the long reference documents so agents
// can read one section by line range instead of loading a whole playbook.
//
//   node scripts/build-reference-index.mjs          # write indexes
//   node scripts/build-reference-index.mjs --check  # fail if an index is stale
//
// Output is deterministic (no timestamps) so --check can diff it.

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const playbookDir = path.join(root, "doc/reference/aw-v9/playbooks");
const playbookIndexDir = path.join(playbookDir, "index");
const briefDir = path.join(root, "doc/reference/blentera-v10");
const briefFile = "Blentera_Master_Build_Brief_V10_FINAL_v4.0_2026-10-18.md";

// Headings deeper than this are left out of the per-document index to keep it small.
const PLAYBOOK_MAX_LEVEL = 2;
const BRIEF_MAX_LEVEL = 2;

const START_HERE = /executive|start here|reading map|decisive conclusion|synthesis/i;
const CHECKLIST = /checklist/i;

export function parseHeadings(text) {
  const lines = text.split("\n");
  const headings = [];
  let fence = null;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const fenceMatch = line.match(/^\s*(```+|~~~+)/);
    if (fenceMatch) {
      if (!fence) fence = fenceMatch[1][0];
      else if (fenceMatch[1][0] === fence) fence = null;
      continue;
    }
    if (fence) continue;
    const m = line.match(/^(#{1,6})\s+(.*?)\s*#*\s*$/);
    if (m) headings.push({ level: m[1].length, title: m[2].replace(/\|/g, "\\|"), line: i + 1 });
  }
  // A section ends right before the next heading of the same or higher level.
  for (let i = 0; i < headings.length; i++) {
    let end = lines.length;
    for (let j = i + 1; j < headings.length; j++) {
      if (headings[j].level <= headings[i].level) {
        end = headings[j].line - 1;
        break;
      }
    }
    headings[i].end = end;
  }
  return { headings, lineCount: lines.length };
}

export function renderIndex({ relPath, title, text, maxLevel }) {
  const { headings, lineCount } = parseHeadings(text);
  const bytes = Buffer.byteLength(text, "utf8");
  const range = (h) => `L${h.line}-${h.end}`;
  const startHere = headings.filter((h) => h.level <= 3 && START_HERE.test(h.title));
  const checklists = headings.filter((h) => h.level <= 3 && CHECKLIST.test(h.title));
  const out = [];
  out.push(`# Index: ${title}`);
  out.push("");
  out.push("Generated by `scripts/build-reference-index.mjs`. Do not edit by hand.");
  out.push("");
  out.push(`- Source: \`${relPath}\``);
  out.push(`- Size: ${lineCount} lines, ${bytes} bytes (about ${Math.round(bytes / 4000)}k tokens). Never read it whole.`);
  out.push(`- Read a section with a line range, for example \`sed -n '${headings[0]?.line ?? 1},${headings[0]?.end ?? 40}p' ${relPath}\`.`);
  out.push("");
  out.push("## Start here");
  out.push("");
  if (startHere.length === 0) out.push("- (no executive or summary heading found)");
  for (const h of startHere.slice(0, 6)) out.push(`- ${range(h)} ${h.title}`);
  out.push("");
  out.push("## Checklists");
  out.push("");
  if (checklists.length === 0) out.push("- (no checklist heading found)");
  for (const h of checklists.slice(0, 12)) out.push(`- ${range(h)} ${h.title}`);
  out.push("");
  out.push(`## Sections (H1-H${maxLevel})`);
  out.push("");
  for (const h of headings) {
    if (h.level > maxLevel) continue;
    out.push(`${"  ".repeat(h.level - 1)}- ${range(h)} ${h.title}`);
  }
  out.push("");
  return { content: out.join("\n"), lineCount, bytes, startHere, checklists };
}

function firstTitle(text, fallback) {
  const m = text.match(/^#\s+(.+)$/m);
  return (m ? m[1].trim() : fallback).replace(/\|/g, "\\|");
}

export function buildReferenceIndexes() {
  const outputs = new Map();

  const playbooks = readdirSync(playbookDir)
    .filter((f) => f.endsWith(".md"))
    .sort();
  const summaryRows = [];
  for (const file of playbooks) {
    const relPath = `doc/reference/aw-v9/playbooks/${file}`;
    const text = readFileSync(path.join(playbookDir, file), "utf8");
    const title = firstTitle(text, file);
    const result = renderIndex({ relPath, title, text, maxLevel: PLAYBOOK_MAX_LEVEL });
    outputs.set(path.join(playbookIndexDir, file), result.content);
    const firstStart = result.startHere[0];
    const lastChecklist = result.checklists[0];
    summaryRows.push(
      `| [${file.replace(/\.md$/, "")}](${file}) | ${result.lineCount} | ~${Math.round(result.bytes / 4000)}k | ${
        firstStart ? `L${firstStart.line}` : "-"
      } | ${lastChecklist ? `L${lastChecklist.line}` : "-"} |`,
    );
  }

  outputs.set(
    path.join(playbookIndexDir, "README.md"),
    [
      "# Playbook indexes",
      "",
      "Generated by `scripts/build-reference-index.mjs`. Do not edit by hand.",
      "",
      "Each playbook is 20k-75k tokens. Read the index first, then only the line ranges you need:",
      "the executive section, the checklist chapter and the chapter for your change.",
      "The router skills in `.claude/skills/pb-*` say which playbooks and chapters fit which change.",
      "Applicability per playbook is in `doc/reference/aw-v9/README.md`.",
      "",
      "| Index | Lines | Tokens | Start here | First checklist |",
      "|---|---|---|---|---|",
      ...summaryRows,
      "",
    ].join("\n"),
  );

  {
    const relPath = `doc/reference/blentera-v10/${briefFile}`;
    const text = readFileSync(path.join(briefDir, briefFile), "utf8");
    const result = renderIndex({
      relPath,
      title: firstTitle(text, briefFile),
      text,
      maxLevel: BRIEF_MAX_LEVEL,
    });
    outputs.set(path.join(briefDir, "index.md"), result.content);
  }
  return outputs;
}

function main() {
  const outputs = buildReferenceIndexes();
  const check = process.argv.includes("--check");
  const stale = [];
  for (const [file, content] of outputs) {
    const current = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (current === content) continue;
    if (check) {
      stale.push(path.relative(root, file));
    } else {
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, content);
    }
  }

  if (check && stale.length > 0) {
    console.error(`Stale reference indexes (run node scripts/build-reference-index.mjs):\n${stale.join("\n")}`);
    process.exit(1);
  }
  console.log(`${check ? "Checked" : "Wrote"} ${outputs.size} reference indexes.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
